"""PII accuracy evaluator.

Runs the PII detection engine against seeded documents and compares
detected entities against ground truth using MUC/CoNLL-style partial
(token-overlap) matching.

Matching semantics (R8 amendment): a detection ``(value, type)`` counts
as correct when

- the ``type`` matches exactly (case-insensitive), AND
- after lowercasing and stripping, the detection value is a substring of
  the ground-truth value, OR the ground-truth value is a substring of the
  detection value, OR their token sets share at least one non-trivial token
  (tokens are split on whitespace and non-alphanumerics).

This is deterministic and pure. Note the corpus is synthetic
(``tests/fixtures/pii/seeded_contracts/``) — generated by
``tests/fixtures/pii/generate_seeded.py`` — so accuracy numbers reflect
detection on templated documents, not real-world contracts.
"""

import re
from collections import Counter
from collections.abc import Callable

from openreview_cli.benchmark.models import MetricValue

# Entity types from ground_truth.json
PII_ENTITY_TYPES = frozenset(
    {
        "PERSON",
        "EMAIL_ADDRESS",
        "PHONE_NUMBER",
        "LOCATION",
        "DATE_TIME",
        "AMOUNT",
        "TAX_ID",
        "ACCT",
        "ID_DOCUMENT",
        "REG_NUMBER",
        "ORGANIZATION",
    }
)


def _tokenize_match(value: str) -> list[str]:
    """Split a value into non-trivial tokens on whitespace + non-alphanumerics."""
    return [tok for tok in re.split(r"[^0-9A-Za-z]+", value) if tok]


def _values_match(
    gt_value: str,
    det_value: str,
    gt_type: str = "",
    det_type: str = "",
) -> bool:
    """Return True when a detection value matches a ground-truth value.

    MUC/CoNLL-style partial matching: type must match exactly (case-insensitive)
    and the values must overlap as a substring or via a shared non-trivial token.
    """
    if gt_type and det_type and gt_type.lower() != det_type.lower():
        return False

    gt_norm = gt_value.strip().lower()
    det_norm = det_value.strip().lower()

    if gt_norm == det_norm:
        return True

    # Empty strings are special-cased: "" is a substring of everything, so only
    # an empty value may match an empty value (avoids trivial all-match).
    if not gt_norm or not det_norm:
        return False

    # Substring overlap either direction. Require a minimum length so a single
    # common character (e.g. "$" in "$1" or "a" in "AutoName") is not treated
    # as a match — that would inflate precision with trivial fragments.
    if len(det_norm) >= 2 and len(gt_norm) >= 2 and (det_norm in gt_norm or gt_norm in det_norm):
        return True

    # Token-set overlap: at least one non-trivial token in common.
    gt_tokens = _tokenize_match(gt_norm)
    det_tokens = _tokenize_match(det_norm)
    return not set(gt_tokens).isdisjoint(set(det_tokens))


def evaluate_pii_accuracy(
    documents: list[tuple[str, str, list[dict[str, str]]]],
    detect_fn: Callable[[str], list[dict[str, str]]],
) -> dict[str, MetricValue]:
    """Evaluate PII detection accuracy against ground truth.

    Args:
        documents: List of (doc_id, text, ground_truth_entities) tuples
        detect_fn: Function that takes text and returns list of
                   {'value': str, 'type': str} detections

    Returns:
        Dict of metric_name -> MetricValue, including per-type breakdown
    """
    all_predictions: list[bool] = []
    all_gt_hits: list[bool] = []  # one entry per GT entity (may exceed #detections
    # when a single detection covers multiple same-type GT entities)
    per_type_total: Counter[str] = Counter()
    per_type_correct: Counter[str] = Counter()

    for _doc_id, text, gt_entities in documents:
        detected = detect_fn(text)

        # Match each detection against every GT entity of the same type.
        # (Exact-duplicate detections collapse via the visited set.)
        detections: list[tuple[str, str]] = [(d["value"], d["type"]) for d in detected]
        gt_entities_by_type: dict[str, list[str]] = {}
        for g in gt_entities:
            gt_entities_by_type.setdefault(g["type"], []).append(g["value"])

        visited: set[tuple[str, str]] = set()
        for det_value, det_type in detections:
            key = (det_value.strip().lower(), det_type)
            if key in visited:
                continue
            visited.add(key)

            matched = False
            for gt_value in gt_entities_by_type.get(det_type, []):
                if _values_match(gt_value, det_value, det_type, det_type):
                    matched = True
                    break
            all_predictions.append(matched)

        # Per-type totals + correct counts, one per GT entity. A single
        # detection may cover several GT entities of the same type (e.g. a
        # merged span "AutoCompanyA1 Inc. and AutoCompanyB1 LLC") — each GT
        # entity is credited independently (MUC entity-level counting).
        for g in gt_entities:
            gt_type = g["type"]
            if gt_type not in PII_ENTITY_TYPES:
                continue
            per_type_total[gt_type] += 1
            gt_value = g["value"]
            hit = any(_values_match(gt_value, d["value"], gt_type, d["type"]) for d in detected)
            all_gt_hits.append(hit)
            if hit:
                per_type_correct[gt_type] += 1

    metrics: dict[str, MetricValue] = {}

    # Overall metrics
    if all_predictions:
        total_predicted_correct = sum(all_predictions)
        total_gt_correct = sum(all_gt_hits)
        total_ground_truths = sum(per_type_total.values())
        total_precision = total_predicted_correct / len(all_predictions)
        total_recall = total_gt_correct / total_ground_truths if total_ground_truths else 0.0
        # F1 must be the harmonic mean of the REPORTED precision and recall.
        # Precision and recall use different TP definitions (detection-centric
        # vs GT-centric), so passing a single TP count to _f1_from_counts would
        # produce a value inconsistent with the reported P/R.
        overall_f1 = (
            2 * total_precision * total_recall / (total_precision + total_recall)
            if (total_precision + total_recall) > 0
            else 0.0
        )

        metrics["pii_recall"] = MetricValue(
            value=total_recall, n=total_ground_truths, unit="recall"
        )
        metrics["pii_precision"] = MetricValue(
            value=total_precision, n=len(all_predictions), unit="precision"
        )
        metrics["pii_f1"] = MetricValue(value=overall_f1, n=total_ground_truths, unit="f1")
    else:
        # No detections: report zero recall/precision/F1. n=1 satisfies the
        # MetricValue n>0 invariant while signaling a single evaluated corpus.
        metrics["pii_recall"] = MetricValue(value=0.0, n=1, unit="recall")
        metrics["pii_precision"] = MetricValue(value=0.0, n=1, unit="precision")
        metrics["pii_f1"] = MetricValue(value=0.0, n=1, unit="f1")

    # Per-type breakdown
    for entity_type, total in per_type_total.items():
        correct = per_type_correct[entity_type]
        type_recall = correct / total
        metrics[f"pii_recall_{entity_type.lower()}"] = MetricValue(
            value=type_recall, n=total, unit="recall"
        )

    return metrics
